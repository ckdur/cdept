//! The start-up file CDePT generates for the xschem engine.
//!
//! xschem finds a symbol named `library/cell.sym` by trying every folder on its
//! `XSCHEM_LIBRARY_PATH`. So for each library of the project, the *parent* of the
//! library folder goes on that path, and schematics refer to symbols as
//! `<library folder>/<file>` (flat layout) or `<library folder>/<cell>/<view>/<file>`
//! (cells layout). Stock xschem resolves the same references with the same path.
//!
//! The file is Tcl, like any `xschemrc`. The helper puts xschem's own `devices` library
//! on the path before reading it, so both `res.sym` and `devices/res.sym` resolve.

use std::path::{Path, PathBuf};

use super::tcl;
use crate::Project;

/// The start-up script for `project`.
pub fn startup_script(project: &Project) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "# Generated by CDePT for project {}. Rewritten at every start: do not edit.\n",
        tcl::quote(&project.name)
    ));
    let mut seen: Vec<&Path> = Vec::new();
    for library in &project.libraries {
        if let Some(error) = &library.error {
            out.push_str(&format!(
                "# library {} skipped: {}\n",
                library.name,
                error.replace('\n', " ")
            ));
            continue;
        }
        let Some(parent) = library.path.parent() else {
            continue;
        };
        if seen.contains(&parent) {
            continue;
        }
        seen.push(parent);
        out.push_str(&format!(
            "append XSCHEM_LIBRARY_PATH : {}\n",
            tcl::quote(&parent.to_string_lossy())
        ));
    }
    out
}

/// The folders xschem searches for the project's libraries, in order: the parent folder
/// of every usable library. xschem's own libraries come before these.
pub fn search_path(project: &Project) -> Vec<PathBuf> {
    let mut out: Vec<PathBuf> = Vec::new();
    for library in project.libraries.iter().filter(|l| l.error.is_none()) {
        if let Some(parent) = library.path.parent()
            && !out.iter().any(|seen| seen == parent)
        {
            out.push(parent.to_path_buf());
        }
    }
    out
}

/// How a schematic refers to `file` (a symbol or schematic inside one of the project's
/// libraries): its path relative to the parent of the library folder.
pub fn reference(project: &Project, file: &Path) -> Option<String> {
    project
        .libraries
        .iter()
        .filter(|library| library.error.is_none())
        .find_map(|library| {
            let parent = library.path.parent()?;
            file.strip_prefix(&library.path).ok()?;
            let relative = file.strip_prefix(parent).ok()?;
            Some(relative.to_string_lossy().into_owned())
        })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::AddLibrary;

    #[test]
    fn library_parents_go_on_the_search_path_once() {
        let dir = tempfile::tempdir().unwrap();
        let mut project = Project::create(dir.path(), Some("demo")).unwrap();
        let options = || AddLibrary {
            create: true,
            ..Default::default()
        };
        project
            .add_library("analog", "libs/analog", options())
            .unwrap();
        project
            .add_library("digital", "libs/digital", options())
            .unwrap();
        project
            .add_library("other", "elsewhere/other", options())
            .unwrap();

        let script = startup_script(&project);
        let root = project.root.clone();
        let libs = tcl::quote(&root.join("libs").to_string_lossy());
        let elsewhere = tcl::quote(&root.join("elsewhere").to_string_lossy());
        assert_eq!(
            script
                .matches(&format!("append XSCHEM_LIBRARY_PATH : {libs}\n"))
                .count(),
            1,
            "{script}"
        );
        assert!(script.contains(&format!("append XSCHEM_LIBRARY_PATH : {elsewhere}\n")));

        let symbol = root.join("libs/analog/ota/symbol/ota.sym");
        assert_eq!(
            reference(&project, &symbol).as_deref(),
            Some("analog/ota/symbol/ota.sym")
        );
        assert_eq!(reference(&project, Path::new("/nowhere/x.sym")), None);
    }

    #[test]
    fn unresolved_libraries_are_skipped() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(
            dir.path().join(crate::PROJECT_FILE),
            "name = \"demo\"\n[libraries]\npdk = \"$CDEPT_TEST_UNSET_VARIABLE/lib\"\n",
        )
        .unwrap();
        let project = Project::load(dir.path()).unwrap();
        assert!(project.library("pdk").unwrap().error.is_some());

        let script = startup_script(&project);
        assert!(script.contains("# library pdk skipped"), "{script}");
        assert!(!script.contains("append"), "{script}");
    }
}
